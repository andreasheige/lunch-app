export function t(key, ...args) {
  const text = TEXTS[LANG][key] ?? TEXTS.sv[key] ?? key;
  return typeof text === 'function' ? text(...args) : text;
}

// One decimal, with the decimal comma in Swedish.
export const num = (n) => (LANG === 'sv' ? n.toFixed(1).replace('.', ',') : n.toFixed(1));

// Static page text: [data-i18n] sets textContent, [data-i18n-label] aria-label; <body data-title> the tab title.
export function applyStatic() {
  document.documentElement.lang = LANG;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll('[data-i18n-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nLabel));
  }
  if (document.body.dataset.title) document.title = t(document.body.dataset.title);
}

// The nav button names the other language; choosing it reloads the page in that language.
export function setupLangToggle() {
  const button = document.getElementById('lang-toggle');
  if (!button) return;
  const other = LANG === 'sv' ? 'en' : 'sv';
  button.lang = other;
  button.addEventListener('click', () => {
    try {
      localStorage.setItem(LANG_KEY, other);
    } catch {}
    location.reload();
  });
}

